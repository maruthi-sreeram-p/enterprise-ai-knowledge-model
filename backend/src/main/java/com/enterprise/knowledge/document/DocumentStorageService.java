package com.enterprise.knowledge.document;

import com.enterprise.knowledge.common.exception.BadRequestException;
import com.enterprise.knowledge.common.exception.DocumentProcessingException;
import com.enterprise.knowledge.config.AppProperties;
import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.UUID;

/**
 * Stores uploaded files on the local filesystem.
 *
 * The filesystem is used rather than object storage because it keeps the
 * project runnable with nothing but Docker Compose. The service is small and
 * self-contained, so swapping in S3 later means replacing this one class.
 *
 * Files are laid out as {@code <root>/<tenantId>/<documentId>.<ext>}. The stored
 * name is generated, never taken from the upload, which removes any possibility
 * of a crafted filename escaping the storage root or colliding with another
 * tenant's file.
 */
@Service
public class DocumentStorageService {

    private static final Logger log = LoggerFactory.getLogger(DocumentStorageService.class);

    private final Path storageRoot;
    private final long maxFileSizeBytes;

    public DocumentStorageService(AppProperties properties) {
        this.storageRoot = Paths.get(properties.getStorage().getRoot()).toAbsolutePath().normalize();
        this.maxFileSizeBytes = properties.getStorage().getMaxFileSizeBytes();
    }

    @PostConstruct
    void createStorageRoot() {
        try {
            Files.createDirectories(storageRoot);
            log.info("Document storage root: {}", storageRoot);
        } catch (IOException ex) {
            throw new IllegalStateException("Could not create storage root " + storageRoot, ex);
        }
    }

    /**
     * Writes an upload to disk.
     *
     * @return the path relative to the storage root, for recording on the document
     */
    public String store(MultipartFile file, UUID tenantId, UUID documentId, String extension) {
        if (file.isEmpty()) {
            throw new BadRequestException("The uploaded file is empty.");
        }
        if (file.getSize() > maxFileSizeBytes) {
            throw new BadRequestException(
                    "The uploaded file exceeds the maximum size of "
                            + (maxFileSizeBytes / (1024 * 1024)) + " MB.");
        }

        Path tenantDirectory = storageRoot.resolve(tenantId.toString());
        Path target = tenantDirectory.resolve(documentId + "." + extension);

        try {
            Files.createDirectories(tenantDirectory);
            try (InputStream input = file.getInputStream()) {
                Files.copy(input, target, StandardCopyOption.REPLACE_EXISTING);
            }
        } catch (IOException ex) {
            throw new DocumentProcessingException("The uploaded file could not be saved.", ex);
        }

        return storageRoot.relativize(target).toString().replace('\\', '/');
    }

    /**
     * Resolves a stored path back to an absolute one.
     *
     * The result is checked to be inside the storage root. The stored value is
     * generated by this service and so should always be safe, but the check
     * means a corrupted or hand-edited database row cannot turn into a read of
     * an arbitrary file.
     */
    public Path resolve(String relativePath) {
        Path resolved = storageRoot.resolve(relativePath).normalize();
        if (!resolved.startsWith(storageRoot)) {
            throw new DocumentProcessingException("Refusing to read a file outside the storage root.");
        }
        return resolved;
    }

    public boolean exists(String relativePath) {
        return Files.isRegularFile(resolve(relativePath));
    }

    /**
     * Deletes a stored file. A missing file is not an error: the document row is
     * being removed anyway, and failing here would leave orphaned metadata.
     */
    public void delete(String relativePath) {
        try {
            boolean deleted = Files.deleteIfExists(resolve(relativePath));
            if (!deleted) {
                log.warn("Stored file {} was already gone when deleting", relativePath);
            }
        } catch (IOException ex) {
            log.error("Could not delete stored file {}", relativePath, ex);
        }
    }
}
