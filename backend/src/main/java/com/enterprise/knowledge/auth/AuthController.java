package com.enterprise.knowledge.auth;

import com.enterprise.knowledge.auth.dto.AuthResponse;
import com.enterprise.knowledge.auth.dto.LoginRequest;
import com.enterprise.knowledge.auth.dto.RegisterRequest;
import com.enterprise.knowledge.user.dto.UserResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/auth")
@Tag(name = "Authentication")
public class AuthController {

    private final AuthService authService;

    public AuthController(AuthService authService) {
        this.authService = authService;
    }

    @PostMapping("/register")
    @Operation(summary = "Register a new organization and its first administrator")
    public ResponseEntity<AuthResponse> register(@Valid @RequestBody RegisterRequest request) {
        return ResponseEntity.status(HttpStatus.CREATED).body(authService.register(request));
    }

    @PostMapping("/login")
    @Operation(summary = "Exchange email and password for an access token")
    public ResponseEntity<AuthResponse> login(@Valid @RequestBody LoginRequest request) {
        return ResponseEntity.ok(authService.login(request));
    }

    @GetMapping("/me")
    @Operation(summary = "Return the currently authenticated user")
    public ResponseEntity<UserResponse> currentUser(@AuthenticationPrincipal AuthenticatedUser principal) {
        return ResponseEntity.ok(new UserResponse(
                principal.getId(), principal.getTenantId(), principal.getName(),
                principal.getEmail(), principal.getRole(), true, null));
    }
}
